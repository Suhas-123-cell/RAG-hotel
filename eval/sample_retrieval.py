"""Regenerate outputs/sample_outputs.md: retrieval-only output of the current pipeline.

No LLM is called, so the file contains no generated answers.

Run from the repo root:
    python -m eval.sample_retrieval
"""
import logging
from datetime import datetime, timezone
from pathlib import Path

import config

OUT_PATH = Path(config.OUTPUTS_DIR) / "sample_outputs.md"
EXTRA_QUERIES = [
    "Compare bathroom essentials at The Azure Grand and Northstar Capsule Lodge.",
    "Which hotels do not have televisions in the rooms?",
]
PREVIEW_CHARS = 130


def _preview(text: str) -> str:
    text = " ".join(text.split())
    return text if len(text) <= PREVIEW_CHARS else text[:PREVIEW_CHARS].rstrip() + "..."


def _table(chunks: list, score_key: str | None) -> list[str]:
    lines = ["| # | chunk_id | hotel | category | score | text preview |", "|---|---|---|---|---:|---|"]
    for i, c in enumerate(chunks, start=1):
        score = f"{c[score_key]:.4f}" if score_key else "-"
        lines.append(f"| {i} | {c['chunk_id']} | {c['hotel_name']} | {c['category']} | {score} | {_preview(c['text']).replace('|', '/')} |")
    return lines


def render(pipeline, queries: list[str]) -> str:
    lines = [
        "# StayChat RAG - sample retrieval output",
        "",
        f"Generated by `python -m eval.sample_retrieval` on {datetime.now(timezone.utc):%Y-%m-%d} "
        "from the current code and `data/hotel_documents.json`.",
        "",
        "This file shows retrieval only: the top RRF chunks and the support chunks the pipeline "
        "adds. It contains no LLM answers, because generating them needs a Groq API key. "
        "Run `python app.py` or `python main.py` with `GROQ_API_KEY` set to see answers. "
        "RRF scores are small by construction (a chunk ranked first by both systems scores 2/61, about 0.033), "
        "so they are not similarity scores. Chunk text is lower-cased by the preprocessor.",
        "",
        "Retrieval quality numbers are in [`eval/results.md`](../eval/results.md).",
        "",
    ]
    for n, query in enumerate(queries, start=1):
        context = pipeline.build_context(query)
        lines += [f"## Query {n}: {query}", "", f"### Top {config.DEFAULT_K} RRF chunks", ""]
        lines += _table(context["retrieved"][: config.DEFAULT_K], "rrf_score")
        lines += ["", "### Support chunks added by `src/pipeline.py`", ""]
        if context["support_chunks"]:
            lines += _table(context["support_chunks"], None)
        else:
            lines.append("None for this query.")
        lines += ["", f"Chunks passed to the generator: {len(context['generation_chunks'])}", ""]
    return "\n".join(lines)


def main() -> None:
    from src.pipeline import RAGPipeline

    pipeline = RAGPipeline(load_generator=False)
    logging.getLogger().setLevel(logging.WARNING)
    OUT_PATH.write_text(render(pipeline, config.DEMO_QUERIES + EXTRA_QUERIES), encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
